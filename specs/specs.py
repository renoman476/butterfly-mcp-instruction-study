STYLE_NAME = {'N': '서술형', 'T': '기술형', 'Q': '수치형', 'M': '혼합형'}
CUT_NAME = {0: '전체 구간', 1: 'CUT 1', 2: 'CUT 2', 3: 'CUT 3', 4: 'CUT 4', 5: 'CUT 5'}


def req_text(r, style):
    rid, cut, n, t, q = r
    if style == 'N': return n
    if style == 'T': return t
    if style == 'Q': return q
    if style == 'M': return '%s (수치 기준: %s)' % (n, q)


def build_prompt(style, out_path):
    lines = [HEADER.format(base=BASE, out=out_path)]
    for cut in (1, 2, 3, 4, 5, 0):
        rs = [r for r in REQS if r[1] == cut]
        if not rs:
            continue
        lines.append('[%s]' % CUT_NAME[cut])
        for r in rs:
            lines.append('- %s' % req_text(r, style))
        lines.append('')
    return '\n'.join(lines)


def build_rework(style, failed_ids, out_path):
    rs = [r for r in REQS if r[0] in failed_ids]
    lines = ['[추가 수정 지시] 방금 저장한 씬을 검토한 결과, 아래 요구사항이 아직 충족되지 않았다. '
             '나머지는 유지하면서 아래 항목을 수정하고 {} 로 저장한 뒤 보고해줘.'.format(out_path), '']
    for r in rs:
        lines.append('- %s' % req_text(r, style))
    return '\n'.join(lines)


